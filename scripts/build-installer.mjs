import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export const output = 'installer/zche_tcmb_install.prog.abap';
const types = ['DOMA', 'DTEL', 'TABL', 'INTF', 'CLAS', 'PROG'];
const literal = (s) => '`' + s.replaceAll('`', '``') + '`';
function assign(target, value) {
  const chunks = value.match(/[\s\S]{1,100}/gu) ?? [''];
  return `${target} = ${chunks.map(literal).join('\n  && ')}.\n`;
}
export async function build() {
  const names = (await readdir(path.join(root, 'src'))).sort();
  const objects = [];
  for (const type of types) {
    const selected = names.filter((n) => n.endsWith(`.${type.toLowerCase()}.xml`));
    if (type === 'TABL') selected.sort((a,b) => Number(!a.startsWith('zche_tcmb_prof.')) - Number(!b.startsWith('zche_tcmb_prof.')) || a.localeCompare(b));
    for (const name of selected) {
      const xml = (await readFile(path.join(root, 'src', name), 'utf8')).replaceAll('\r\n', '\n').trim();
      const nameParts = name.split('.');
      const object = { name: nameParts[0].toUpperCase(), type, xml: xml.match(/<asx:abap[\s\S]*<\/asx:abap>/u)?.[0]?.replace(/>\s+</gu, '><') };
      if (!object.xml) throw new Error(`No ABAP XML payload: ${name}`);
      for (const [key, extension] of [['source', `${type.toLowerCase()}.abap`], ['tests', 'clas.testclasses.abap']]) {
        const file = `${nameParts[0]}.${extension}`;
        if ((key === 'source' || type === 'CLAS') && names.includes(file)) {
          object[key] = (await readFile(path.join(root, 'src', file), 'utf8')).replaceAll('\r\n', '\n').trimEnd();
        }
      }
      objects.push(object);
    }
  }
  if (!objects.some((o) => o.name === 'ZCHE_TCMB_CONFIG')) throw new Error('Missing configuration report');
  const manifest = JSON.stringify(objects);
  const hash = createHash('sha256').update(manifest).digest('hex');
  let payload = '\nFORM embedded_payload.\n  DATA item TYPE ty_item.\n';
  for (const object of objects) {
    payload += `  CLEAR item.\n  item-kind = '${object.type}'.\n  item-name = '${object.name}'.\n`;
    payload += assign('  item-xml', object.xml);
    for (const key of ['source', 'tests']) {
      for (const line of (object[key]?.split('\n') ?? [])) {
        payload += assign('  gv_line', line) + `  APPEND gv_line TO item-${key}.\n`;
      }
    }
    payload += '  APPEND item TO gt_items.\n';
  }
  payload += 'ENDFORM.\n';
  const template = (await readFile(path.join(root, 'installer/template.abap'), 'utf8')).replaceAll('\r\n', '\n');
  return { text: `* Generated by scripts/build-installer.mjs; edit src/ and template instead.\n* Payload SHA-256: ${hash}\n${template.trimEnd()}\n${payload}`, objects, hash };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await build();
  if (process.argv.includes('--check')) {
    if ((await readFile(path.join(root, output), 'utf8')).replaceAll('\r\n', '\n') !== result.text) {
      throw new Error('Installer is stale. Run npm run build:installer.');
    }
    console.log(`Installer matches ${result.objects.length} source objects (${result.hash}).`);
  } else {
    await writeFile(path.join(root, output), result.text);
    console.log(`Built ${output}: ${result.objects.length} objects.`);
  }
}
